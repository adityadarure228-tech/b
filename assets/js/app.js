const filterButtons = document.querySelectorAll('[data-filter]');
const movieCards = document.querySelectorAll('[data-category]');
filterButtons.forEach((button) => {
  button.addEventListener('click', () => {
    const category = button.dataset.filter;
    filterButtons.forEach((btn) => btn.classList.remove('btn-primary'));
    button.classList.add('btn-primary');
    movieCards.forEach((card) => {
      const matches = category === 'all' || card.dataset.category.toLowerCase().includes(category.toLowerCase());
      card.classList.toggle('hidden', !matches);
    });
  });
});

const scrollBackground = document.querySelector('[data-scroll-bg]');
const observedCards = document.querySelectorAll('[data-bg-image]');
if (scrollBackground && observedCards.length) {
  const setBackground = (imageUrl) => {
    scrollBackground.style.backgroundImage = `url(${imageUrl})`;
  };
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        setBackground(entry.target.dataset.bgImage);
      }
    });
  }, { threshold: 0.45 });
  observedCards.forEach((card) => observer.observe(card));
  setBackground(observedCards[0].dataset.bgImage);
}

